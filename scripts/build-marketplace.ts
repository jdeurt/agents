import { checkOutputParents, filesIn, inside, pruneEmptyDirectories } from "./build-files.ts";
import { mkdir, mkdtemp, realpath, rm, stat, symlink } from "node:fs/promises";
import { readFile, writeFile } from "./io.ts";
import type { BuiltFile } from "./types.ts";
import { EXECUTABLE_BITS } from "./file-modes.ts";
import { TOML } from "bun";
import { catalogs } from "./catalogs.ts";
import { compilePlugin } from "./compile-plugin.ts";
import { fileURLToPath } from "node:url";
import { parseRegistry } from "./validation.ts";
import path from "node:path";
import { tmpdir } from "node:os";
import { withResolvedSources } from "./resolve-sources.ts";

const MARKETPLACE_BUILD = ".marketplace-build";

const NODE_MODULES = "node_modules";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
/**
Serialize a value as formatted JSON with a final newline.
@param value - Value to serialize.
@returns The formatted JSON text.
*/
const json = (value: unknown) => `${JSON.stringify(value, undefined, 2)}\n`;

/**
Append a file path when its generated bytes or executable mode differ.
@param output - Root directory containing the existing build.
@param file - Relative generated file path to compare.
@param value - Expected bytes and file mode.
@param differences - Mutable list that receives a differing file path.
*/
async function recordDifference(output: string, file: string, value: BuiltFile, differences: string[]) {
  const filename = inside(output, file);
  const info = await stat(filename);
  const isExecutable = Boolean(info.mode & EXECUTABLE_BITS);

  if (!value.contents.equals(await readFile(filename)) || isExecutable !== Boolean(value.mode & EXECUTABLE_BITS)) {
    differences.push(file);
  }
}

/**
Compare an existing build with expected files and known stale paths.
@param output - Root directory containing the existing build.
@param expected - Expected files indexed by relative path.
@param stale - Existing file paths absent from the expected build.
@returns The stale, missing, or changed file paths.
*/
async function compareBuild(output: string, expected: Map<string, BuiltFile>, stale: string[]) {
  const differences = [...stale];

  for (const [file, value] of expected) {
    try {
      await recordDifference(output, file, value, differences);
    } catch (error) {
      if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) {
        throw error;
      }

      differences.push(file);
    }
  }

  return differences;
}

/**
Replace generated files, remove stale files, and prune empty output directories.
@param output - Root directory to update.
@param expected - Expected files indexed by relative path.
@param stale - Existing file paths to remove.
*/
async function writeBuild(output: string, expected: Map<string, BuiltFile>, stale: string[]) {
  for (const file of stale) {
    await rm(inside(output, file));
  }

  for (const [file, value] of expected) {
    const filename = inside(output, file);

    await mkdir(path.dirname(filename), { recursive: true });
    await rm(filename, { force: true });
    await writeFile(filename, value.contents, { mode: value.mode });
  }

  await pruneEmptyDirectories(path.join(output, "dist"));
}

/**
Create the output directory when the build can write files.
@param output - Destination directory for generated files.
@param shouldCheck - Whether the build must only verify existing files.
@returns The output directory path.
*/
async function prepareOutput(output: string, shouldCheck: boolean) {
  if (!shouldCheck) {
    await mkdir(output, { recursive: true });
  }

  return output;
}

/**
Validate output parents, then verify or write the completed build.
@param output - Destination directory for generated files.
@param shouldCheck - Whether to verify existing output without writing it.
@param expected - Complete expected output indexed by relative path.
@param pluginCount - Number of plugins included in the build.
@returns The counts of plugins and generated files.
*/
async function finishBuild(
  output: string,
  shouldCheck: boolean,
  expected: Map<string, BuiltFile>,
  pluginCount: number
) {
  const actual = await filesIn(path.join(output, "dist"), "dist");
  const stale = actual.filter((file) => !expected.has(file));

  for (const file of expected.keys()) {
    await checkOutputParents(output, file);
  }

  if (shouldCheck) {
    const differences = await compareBuild(output, expected, stale);

    if (differences.length > 0) {
      throw new Error(`Generated files are stale. Run bun run build:\n${differences.join("\n")}`);
    }
  } else {
    await writeBuild(output, expected, stale);
  }

  return { plugins: pluginCount, files: expected.size };
}

/**
Compile resolved plugin sources and catalogs, then verify or write the result.
@param root - Root directory containing resolved sources and the registry.
@param output - Destination directory for generated files.
@param shouldCheck - Whether to verify existing output without writing it.
@returns The counts of plugins and generated files.
*/
async function buildResolvedMarketplace(root: string, output: string, shouldCheck: boolean) {
  const preparedOutput = await prepareOutput(output, shouldCheck);
  const registryText = await readFile(path.join(root, "marketplace.toml"), "utf8");
  const registry = parseRegistry(TOML.parse(registryText));
  const expected = new Map<string, BuiltFile>();
  const temporaryDirectory = await mkdtemp(path.join(tmpdir(), "agents-marketplace-"));
  const staging = await realpath(temporaryDirectory);

  async function compilePlugins() {
    await writeFile(path.join(staging, "package.json"), json({ type: "module" }));
    await symlink(path.join(ROOT, NODE_MODULES), path.join(staging, NODE_MODULES), "dir");

    for (const plugin of registry.plugins) {
      const compiled = await compilePlugin(root, plugin, registry.marketplace.owner, staging);

      for (const [file, content] of compiled) {
        expected.set(file, content);
      }
    }
  }

  try {
    await compilePlugins();
  } finally {
    await rm(staging, { recursive: true, force: true });
  }

  for (const [file, value] of catalogs(registry)) {
    expected.set(file, value);
  }

  return finishBuild(preparedOutput, shouldCheck, expected, registry.plugins.length);
}

/**
Resolve imported sources as needed and build or verify the marketplace.
@param options - Source, output, and verification settings for the build.
@returns The counts of plugins and generated files.
*/
export async function buildMarketplace({
  root = ROOT,
  check = false,
  output = path.join(root, MARKETPLACE_BUILD),
  resolved = false,
} = {}): Promise<{ plugins: number; files: number }> {
  if (!resolved) {
    return withResolvedSources(root, (source) =>
      buildMarketplace({
        root: source,
        check,
        output,
        resolved: true,
      })
    );
  }

  return buildResolvedMarketplace(await realpath(path.resolve(root)), path.resolve(output), check);
}

/**
Parse build command arguments and reject unsupported option combinations.
@param args - Command arguments after the script name.
@returns The check flag and absolute output directory.
*/
function parseOptions(args: string[]) {
  const options = { check: false, output: path.join(ROOT, MARKETPLACE_BUILD) };

  for (let i = 0; i < args.length; i++) {
    const next = args[i + 1];

    if (args[i] === "--check") {
      options.check = true;
    } else if (next && args[i] === "--output" && !next.startsWith("--")) {
      options.output = path.resolve(next);
      i++;
    } else {
      throw new Error("Usage: bun scripts/build-marketplace.ts [--check] [--output directory]");
    }
  }

  return options;
}

/**
Run the marketplace build command and print its output counts.
*/
async function main() {
  const options = parseOptions(process.argv.slice(2));
  const result = await buildMarketplace(options);

  console.log(
    `${options.check ? "Checked" : "Built"} ${String(result.plugins)} plugin(s), ${String(result.files)} generated files.`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
